"use client";

import { useRouter } from "next/navigation";
import { useEffect, useRef, useState, type ReactNode } from "react";
import { Button } from "@/components/ui/Button";
import { EmptyState } from "@/components/ui/EmptyState";
import { Panel } from "@/components/ui/Panel";
import { ProgressBar } from "@/components/ui/ProgressBar";
import { Tag, type TagTone } from "@/components/ui/Tag";
import { TextLink } from "@/components/ui/TextLink";
import type { ViewerEvent, ViewerStep } from "@/features/building-viewer/schema";
import { relativeTime } from "@/features/demo/format";
import { formatClock } from "@/features/workspace/format";

/** The stored model, as the page passes it in. Mirrors ProjectModel (src/features/scout/model.ts). */
export type ModelView = {
  html: string;
  reply: string;
  geocodeStatus: string;
  contextStatus: string;
  drift: boolean;
  generatedAt: string;
  /** Made by the older, code-writing generator: it can't take today's stage (the sky, the ground). */
  stale?: boolean;
};

/** A run that is not this page's own: started when the project was added, or by the agent. */
export type BackgroundRun = { status: "generating"; startedAt: string } | { status: "failed"; error: string } | null;

type StepStatus = "queued" | "running" | "done" | "missing" | "skipped" | "error";

const STEPS: { id: ViewerStep; label: string }[] = [
  { id: "geocode", label: "Find the address" },
  { id: "context", label: "Map the buildings around it" },
  { id: "model", label: "Research and describe the building" },
  { id: "assemble", label: "Build the 3D model" },
];

const STEP_TAG: Record<StepStatus, { tone: TagTone; label: string }> = {
  queued: { tone: "neutral", label: "Queued" },
  running: { tone: "running", label: "Running" },
  done: { tone: "pass", label: "Done" },
  missing: { tone: "neutral", label: "Not found" },
  skipped: { tone: "neutral", label: "Skipped" },
  error: { tone: "fail", label: "Failed" },
};

type Run = {
  phase: "idle" | "running" | "error";
  steps: Record<ViewerStep, { status: StepStatus; detail?: string }>;
  startedAt: number | null;
  error: string | null;
};

const QUEUED: Run["steps"] = {
  geocode: { status: "queued" },
  context: { status: "queued" },
  model: { status: "queued" },
  assemble: { status: "queued" },
};

function useNow(active: boolean): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    if (!active) return;
    const timer = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(timer);
  }, [active]);
  return now;
}

/** "retrieved" / "not retrieved" from the generator, as a plain phrase. */
function found(status: string): string {
  return status === "retrieved" ? "found" : "not found";
}

/** Why a step came back empty, in the operator's words. The generator reports only "not retrieved". */
const MISSING_NOTE: Partial<Record<ViewerStep, string>> = {
  geocode: "No map location for this address, so the model works from the facts alone.",
  context: "Needs the map location, so the buildings around it are left out.",
};

/** A step event as the row's status and note. A lookup that found nothing is "Not found", not "Done". */
function stepState(event: Extract<ViewerEvent, { type: "step" }>): [StepStatus, string | undefined] {
  if (event.status === "start") return ["running", undefined];
  if (event.detail === "not retrieved") return [event.status === "skipped" ? "skipped" : "missing", MISSING_NOTE[event.step]];
  return [event.status, undefined];
}

/** `**bold**` spans as <strong>; the rest as text. */
function inline(text: string): ReactNode[] {
  return text.split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
    part.startsWith("**") && part.endsWith("**") ? <strong key={i}>{part.slice(2, -2)}</strong> : part,
  );
}

/**
 * The model's reply is short markdown: paragraphs, "- " bullets and **bold**. Drawn as that, not as raw markdown,
 * and never as HTML (it is model text).
 */
function ModelNotes({ text }: { text: string }) {
  const blocks: ReactNode[] = [];
  let bullets: string[] = [];
  const flush = () => {
    if (bullets.length === 0) return;
    blocks.push(
      <ul key={`ul-${blocks.length}`} className="flex list-disc flex-col gap-1 pl-5">
        {bullets.map((b, i) => (
          <li key={i}>{inline(b)}</li>
        ))}
      </ul>,
    );
    bullets = [];
  };
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (/^[-*] /.test(line)) {
      bullets.push(line.slice(2));
      continue;
    }
    flush();
    if (line) blocks.push(<p key={`p-${blocks.length}`}>{inline(line.replace(/^#+\s*/, ""))}</p>);
  }
  flush();
  return <div className="flex max-w-[72ch] flex-col gap-3 text-sm leading-[22px] text-pretty">{blocks}</div>;
}

/**
 * A scouted project's 3D model: generated by the building viewer generator from the project's address, scout facts
 * and dossier (POST /api/scout/projects/[project]/model, two to four minutes), stored on the project and shown in a
 * sandboxed frame. While it runs, the four steps show their status.
 *
 * A project added from scouting starts its model by itself. While that run is going, the board says so and reloads
 * the page's data every few seconds, so the model appears when it is saved (the page remounts the board on a new one).
 */
export function ModelBoard({
  projectId,
  initial,
  hasDossier,
  background = null,
}: {
  projectId: string;
  initial: ModelView | null;
  hasDossier: boolean;
  background?: BackgroundRun;
}) {
  const router = useRouter();
  const [model, setModel] = useState<ModelView | null>(initial);
  const [run, setRun] = useState<Run>({ phase: "idle", steps: QUEUED, startedAt: null, error: null });
  const abortRef = useRef<AbortController | null>(null);
  const running = run.phase === "running";
  const elsewhere = !running && background?.status === "generating";
  const now = useNow(running || elsewhere);

  useEffect(() => () => abortRef.current?.abort(), []);

  useEffect(() => {
    if (!elsewhere) return;
    const timer = setInterval(() => router.refresh(), 8000);
    return () => clearInterval(timer);
  }, [elsewhere, router]);

  const setStep = (step: ViewerStep, status: StepStatus, detail?: string) =>
    setRun((r) => ({ ...r, steps: { ...r.steps, [step]: { status, detail } } }));

  const fail = (error: string) =>
    setRun((r) => ({
      ...r,
      phase: "error",
      error,
      steps: Object.fromEntries(
        Object.entries(r.steps).map(([k, v]) => [k, v.status === "running" ? { ...v, status: "error" } : v]),
      ) as Run["steps"],
    }));

  const generate = async () => {
    if (running) return;
    const controller = new AbortController();
    abortRef.current = controller;
    setRun({ phase: "running", steps: QUEUED, startedAt: Date.now(), error: null });
    try {
      const response = await fetch(`/api/scout/projects/${encodeURIComponent(projectId)}/model`, {
        method: "POST",
        signal: controller.signal,
      });
      if (response.status === 409) {
        // A run started elsewhere (on add, by the agent, or by a build). Show it and wait for it instead.
        setRun({ phase: "idle", steps: QUEUED, startedAt: null, error: null });
        router.refresh();
        return;
      }
      if (!response.ok || !response.body) {
        const body = (await response.json().catch(() => ({}))) as { error?: string };
        fail(body.error ?? `The model couldn't start (HTTP ${response.status}).`);
        return;
      }
      const reader = response.body.pipeThrough(new TextDecoderStream()).getReader();
      let buffer = "";
      for (;;) {
        const { value, done } = await reader.read();
        if (done) break;
        buffer += value;
        const lines = buffer.split("\n");
        buffer = lines.pop() ?? "";
        for (const line of lines) {
          if (!line.trim()) continue;
          const event = JSON.parse(line) as ViewerEvent;
          if (event.type === "step") {
            setStep(event.step, ...stepState(event));
          } else if (event.type === "result") {
            setModel({
              html: event.html,
              reply: event.reply,
              geocodeStatus: event.geocode_status,
              contextStatus: event.context_status,
              drift: event.drift,
              generatedAt: new Date().toISOString(),
            });
            setRun({ phase: "idle", steps: QUEUED, startedAt: null, error: null });
            router.refresh();
            return;
          } else if (event.type === "error") {
            fail(event.error);
            return;
          }
        }
      }
      fail("The run stopped before the model was ready. Try again.");
    } catch {
      if (controller.signal.aborted) return;
      fail("Couldn't reach the server. Check your connection and try again.");
    }
  };

  const progress =
    run.phase !== "idle" ? (
      <Panel
        title={running ? "Generating the model" : "The model didn't finish"}
        count={running && run.startedAt ? <span className="app-num">{formatClock((now - run.startedAt) / 1000)}</span> : undefined}
        flush
      >
        <ol aria-label="Model steps" className="divide-y divide-divider">
          {STEPS.map((step, i) => {
            const state = run.steps[step.id];
            const tag = STEP_TAG[state.status];
            return (
              <li key={step.id} className="flex items-start gap-3 px-5 py-4">
                <span className="app-num shrink-0 text-xs leading-[18px] text-muted">{String(i + 1).padStart(2, "0")}</span>
                <span className="flex min-w-0 flex-1 flex-col gap-2">
                  <span className="truncate text-sm leading-[18px] font-semibold">{step.label}</span>
                  <ProgressBar
                    status={
                      state.status === "skipped" || state.status === "missing"
                        ? "done"
                        : state.status === "error"
                          ? "error"
                          : state.status
                    }
                  />
                  {state.detail ? <span className="text-xs leading-4 text-muted">{state.detail}</span> : null}
                </span>
                <span className="w-[72px] shrink-0">
                  <Tag tone={tag.tone}>{tag.label}</Tag>
                </span>
              </li>
            );
          })}
        </ol>
        {run.phase === "error" && run.error ? (
          <div role="alert" className="flex flex-col items-start gap-3 border-t border-divider px-5 py-4">
            <p className="text-[13px] leading-5 break-words text-status-fail-ink">{run.error}</p>
            <Button onClick={generate}>Try again</Button>
          </div>
        ) : null}
      </Panel>
    ) : null;

  const backgroundPanel =
    elsewhere && background?.status === "generating" ? (
      <Panel
        title="Generating the model"
        count={<span className="app-num">{formatClock(Math.max(0, now - Date.parse(background.startedAt)) / 1000)}</span>}
      >
        <div className="flex flex-col gap-3">
          <ProgressBar status="running" />
          <p className="text-[13px] leading-5 text-muted">
            It runs on the server (it starts by itself when a project is added) and takes two to four minutes. It shows here,
            and on every stakeholder&apos;s Shots tab, when it&apos;s done.
          </p>
        </div>
      </Panel>
    ) : null;

  if (!model) {
    return (
      <div className="flex flex-col gap-6">
        {progress}
        {backgroundPanel}
        {running || elsewhere ? null : (
          <Panel flush>
            <EmptyState
              title={background?.status === "failed" ? "The model didn't finish" : "No model yet"}
              description={
                background?.status === "failed"
                  ? `${background.error} Generate it again; it takes two to four minutes.`
                  : hasDossier
                  ? "Generate a 3D model of the building from its address, the scout's facts and its dossier. It takes two to four minutes."
                  : "Generate a 3D model of the building from its address and the scout's facts. It takes two to four minutes. Research the dossier first for a closer model."
              }
              action={
                <Button variant="primary" onClick={generate}>
                  Generate model
                </Button>
              }
            />
          </Panel>
        )}
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-6">
      {progress}
      {backgroundPanel}
      <Panel
        title="Model"
        action={
          <Button onClick={generate} pending={running || elsewhere} pendingLabel="Generating…">
            Generate again
          </Button>
        }
        flush
      >
        <iframe
          title="3D model of the building"
          sandbox="allow-scripts"
          srcDoc={model.html}
          className="block h-[560px] w-full border-0"
        />
        <p className="border-t border-divider px-5 py-3 text-[13px] leading-5 text-muted" suppressHydrationWarning>
          Generated {relativeTime(model.generatedAt)} · map location {found(model.geocodeStatus)} · nearby buildings{" "}
          {found(model.contextStatus)}
          {model.stale ? " · made with an older viewer, so it keeps the old orange stage. Generate again for the sky." : null}
        </p>
      </Panel>

      {model.reply ? (
        <Panel title="What the model assumed">
          <ModelNotes text={model.reply} />
        </Panel>
      ) : null}

      {hasDossier ? null : (
        <p className="text-[13px] leading-5 text-muted">
          No dossier yet, so the model used only the scout&apos;s facts.{" "}
          <TextLink href={`/projects/${projectId}/dossier`}>Research the dossier</TextLink>, then generate again.
        </p>
      )}
    </div>
  );
}
